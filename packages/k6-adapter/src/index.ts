import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { basename, dirname, isAbsolute, relative, resolve, sep } from "node:path";
import { build, type Loader, type Plugin } from "esbuild";
import { SHIM_MODULE_SOURCE } from "./shim.js";

export interface ExportK6Options {
  /** Absolute or cwd-relative path to the `.journey.ts` file. */
  journeyFile: string;
  /** Output path for the emitted k6 script. Wins over `outDir` when both are set. */
  outFile?: string;
  /** Output directory; emitted file is `<outDir>/<basename>.k6.js`. Ignored when `outFile` is set. */
  outDir?: string;
  /**
   * k6 options block to bake into the emitted script as `export const options = {...}`.
   * Same shape as `JourneyOptions['k6']` from `@usejourney/core`; kept loose here so the
   * adapter does not pull a runtime dep on core. JSON-serialized verbatim.
   */
  k6Options?: Record<string, unknown>;
  /**
   * Opt in to custom k6 metrics. Every step records a Trend
   * `<prefix>_<step_slug>_duration` (`res.timings.duration`, ms) and a Counter
   * `<prefix>_<step_slug>_tps`; every completed iteration records
   * `<prefix>_flow_duration` (sum of its step durations) and `<prefix>_flow_tps`.
   * A step's `metric` option overrides its slug (`false` skips it).
   */
  metricsPrefix?: string;
  /**
   * Stop the iteration's remaining steps when a step's `assert` fails,
   * mirroring `journey run`. Default: the failure is recorded as a failed
   * k6 check and the iteration carries on.
   */
  haltOnFailure?: boolean;
  /**
   * Project root that relative `fileFrom()` paths resolve against. Defaults to
   * the nearest ancestor of the journey file holding `journey.config.json`,
   * else `process.cwd()`.
   */
  projectDir?: string;
}

export interface ExportK6Result {
  outFile: string;
  source: string;
}

const HEADER = `// AUTO-GENERATED BY @usejourney/k6-adapter — do not edit by hand.
// Usage: k6 run -e JOURNEY_BASE_URL=https://api.example.com <this-file>
//        (BASE_URL is accepted as a fallback for JOURNEY_BASE_URL)`;

const METRIC_PREFIX_RE = /^[A-Za-z_][A-Za-z0-9_]*$/;
/** Replaced after bundling with the init-time `open()` map. */
const FILES_PLACEHOLDER = "__JOURNEY_PRELOADED_FILES__";

/** Nearest ancestor of `from` (inclusive) containing `journey.config.json`. */
export function findProjectDir(from: string): string | undefined {
  let dir = from;
  for (;;) {
    if (existsSync(resolve(dir, "journey.config.json"))) return dir;
    const parent = dirname(dir);
    if (parent === dir) return undefined;
    dir = parent;
  }
}

function toPosix(p: string): string {
  return sep === "/" ? p : p.split(sep).join("/");
}

/** Path from the emitted script's directory to `abs`, in k6 `open()` form. */
function relFromScript(scriptDir: string, abs: string): string {
  const rel = toPosix(relative(scriptDir, abs));
  if (rel === "") return ".";
  if (isAbsolute(rel)) return rel; // different drive on Windows
  return rel.startsWith("../") || rel === ".." ? rel : `./${rel}`;
}

const FILE_FROM_RE = /\bfileFrom\s*\(\s*(?:"([^"\\\n]*)"|'([^'\\\n]*)'|`([^`\\$]*)`)/g;

/** String-literal `fileFrom("…")` paths in a module's source. */
export function scanFileFromLiterals(source: string): string[] {
  const out: string[] = [];
  FILE_FROM_RE.lastIndex = 0;
  let m: RegExpExecArray | null;
  while ((m = FILE_FROM_RE.exec(source))) out.push((m[1] ?? m[2] ?? m[3])!);
  return out;
}

function loaderFor(path: string): Loader {
  if (/\.[cm]?tsx$/.test(path)) return "tsx";
  if (/\.[cm]?ts$/.test(path)) return "ts";
  if (/\.jsx$/.test(path)) return "jsx";
  return "js";
}

function journeyPlugin(fileRefs: Map<string, string>, initSource: string): Plugin {
  return {
    name: "journey-k6",
    setup(b) {
      // `@usejourney/core` → the k6 shim (a virtual module).
      b.onResolve({ filter: /^@usejourney\/core$/ }, () => ({
        path: "shim",
        namespace: "journey",
      }));
      b.onLoad({ filter: /^shim$/, namespace: "journey" }, () => ({
        contents: SHIM_MODULE_SOURCE,
        loader: "js",
      }));
      b.onResolve({ filter: /^journey:init$/ }, () => ({ path: "init", namespace: "journey" }));
      b.onLoad({ filter: /^init$/, namespace: "journey" }, () => ({
        contents: initSource,
        loader: "js",
      }));
      // k6 built-in modules stay as imports in the emitted script.
      b.onResolve({ filter: /^k6(\/.*)?$/ }, (args) => ({ path: args.path, external: true }));
      // Anything else that isn't a relative/absolute path is an npm package,
      // node builtin, or remote URL — none of which exist in k6. Fail loudly.
      b.onResolve({ filter: /^[^./]/ }, (args) => {
        if (isAbsolute(args.path)) return undefined;
        return {
          errors: [
            {
              text:
                `unsupported import "${args.path}": k6 exports can only import "@usejourney/core", ` +
                `k6 modules ("k6", "k6/…") and relative project files. ` +
                `Inline the helper you need or replace the package with plain code.`,
            },
          ],
        };
      });
      // Collect string-literal fileFrom("…") paths so the init block can
      // pre-load them with open() in the k6 init context.
      b.onLoad({ filter: /\.[cm]?[jt]sx?$/, namespace: "file" }, async (args) => {
        const contents = await readFile(args.path, "utf8");
        for (const p of scanFileFromLiterals(contents)) {
          if (!fileRefs.has(p)) fileRefs.set(p, args.path);
        }
        return { contents, loader: loaderFor(args.path) };
      });
    },
  };
}

function assertNoEntryConflicts(source: string, journeyPath: string, hasK6Options: boolean): void {
  if (/^\s*export\s+default\b/m.test(source) || /\bas\s+default\s*[,}]/.test(source)) {
    throw new Error(
      `${journeyPath}: a journey file cannot \`export default\` — the k6 export generates the ` +
        `default function. Move it to a helper module or drop the export.`,
    );
  }
  const exportsOptions =
    /^\s*export\s+(?:const|let|var|function)\s+options\b/m.test(source) ||
    /^\s*export\s*\{[^}]*\boptions\b[^}]*\}/m.test(source);
  if (hasK6Options && exportsOptions) {
    throw new Error(
      `${journeyPath}: declares both a journey \`k6\` block and \`export const options\`. ` +
        `k6 options are module-scoped — keep only one of them.`,
    );
  }
}

/** Render esbuild's structured errors as `file:line:col: message` lines. */
function formatBuildError(err: unknown): Error {
  const errors = (
    err as {
      errors?: Array<{
        text: string;
        location?: { file: string; line: number; column: number; lineText: string } | null;
      }>;
    }
  ).errors;
  if (!Array.isArray(errors) || errors.length === 0) return err as Error;
  const lines = errors.map((e) => {
    const loc = e.location;
    if (!loc) return e.text;
    const file = isAbsolute(loc.file) ? loc.file : resolve(process.cwd(), loc.file);
    return `${file}:${loc.line}:${loc.column + 1}: ${e.text}\n    ${loc.lineText.trim()}`;
  });
  return new Error(`k6 export failed:\n${lines.join("\n")}`);
}

export async function exportToK6(opts: ExportK6Options): Promise<ExportK6Result> {
  const journeyPath = resolve(process.cwd(), opts.journeyFile);
  const rawSource = await readFile(journeyPath, "utf8");
  assertNoEntryConflicts(rawSource, journeyPath, opts.k6Options !== undefined);

  if (opts.metricsPrefix !== undefined && !METRIC_PREFIX_RE.test(opts.metricsPrefix)) {
    throw new Error(
      `invalid metrics prefix ${JSON.stringify(opts.metricsPrefix)}: use letters, digits and "_" (not starting with a digit)`,
    );
  }

  const fileBase = basename(journeyPath).replace(/\.journey\.ts$/, "");
  const outFile = opts.outFile
    ? resolve(process.cwd(), opts.outFile)
    : opts.outDir
      ? resolve(process.cwd(), opts.outDir, `${fileBase}.k6.js`)
      : resolve(dirname(journeyPath), `${fileBase}.k6.js`);
  const scriptDir = dirname(outFile);
  const projectDir = opts.projectDir
    ? resolve(process.cwd(), opts.projectDir)
    : (findProjectDir(dirname(journeyPath)) ?? process.cwd());
  const rootRel = relFromScript(scriptDir, projectDir);

  const config = {
    ...(opts.metricsPrefix ? { metricsPrefix: opts.metricsPrefix } : {}),
    ...(opts.haltOnFailure ? { haltOnFailure: true } : {}),
    projectRoot: rootRel.endsWith("/") ? rootRel : `${rootRel}/`,
  };
  // Imported before the journey module, so it is evaluated first: a
  // top-level `fileFrom()` in a journey already sees the project root.
  const initSource = `import { __configure } from "@usejourney/core";
__configure(Object.assign(${JSON.stringify(config)}, { files: ${FILES_PLACEHOLDER} }));
`;
  const optionsBlock = opts.k6Options
    ? `export const options = ${JSON.stringify(opts.k6Options, null, 2)};\n`
    : "";
  const entrySource = `import "journey:init";
import { __declareMetrics, __iterate } from "@usejourney/core";
export * from ${JSON.stringify(journeyPath)};
${optionsBlock}
// Custom metrics must be declared in the k6 init context.
__declareMetrics();

export default function () {
  return __iterate();
}
`;

  const fileRefs = new Map<string, string>();
  let source: string;
  try {
    const result = await build({
      stdin: {
        contents: entrySource,
        resolveDir: dirname(journeyPath),
        sourcefile: "journey-k6-entry.js",
        loader: "js",
      },
      bundle: true,
      write: false,
      format: "esm",
      platform: "neutral",
      target: "es2020",
      charset: "utf8",
      logLevel: "silent",
      // Module markers in the output (`// journeys/x.journey.ts`) are
      // project-relative, so emitted scripts don't leak local paths.
      absWorkingDir: projectDir,
      banner: { js: HEADER },
      // Journey projects carry no tsconfig; don't let an ancestor's
      // (e.g. `verbatimModuleSyntax`) change which imports survive.
      tsconfigRaw: {},
      plugins: [journeyPlugin(fileRefs, initSource)],
    });
    source = result.outputFiles[0]!.text;
  } catch (err) {
    throw formatBuildError(err);
  }

  const fileEntries: string[] = [];
  for (const [p, referrer] of fileRefs) {
    const abs = isAbsolute(p) ? p : resolve(projectDir, p);
    if (!existsSync(abs)) {
      throw new Error(
        `${referrer}: fileFrom(${JSON.stringify(p)}) → ${abs} does not exist ` +
          `(fileFrom paths are relative to the project root, ${projectDir})`,
      );
    }
    fileEntries.push(
      `    ${JSON.stringify(p)}: open(${JSON.stringify(relFromScript(scriptDir, abs))}, "b")`,
    );
  }
  const fileMap = fileEntries.length ? `{\n${fileEntries.join(",\n")}\n  }` : "{}";
  if (!source.includes(FILES_PLACEHOLDER)) {
    throw new Error("k6-adapter: internal error — init block missing from the bundle");
  }
  source = source.replace(FILES_PLACEHOLDER, fileMap);

  await mkdir(dirname(outFile), { recursive: true });
  await writeFile(outFile, source, "utf8");
  return { outFile, source };
}
